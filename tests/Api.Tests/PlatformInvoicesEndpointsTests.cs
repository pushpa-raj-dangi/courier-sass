using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using Microsoft.AspNetCore.Mvc.Testing;
using Xunit;

namespace Courier.Api.Tests;

// Uses the same WebApplicationFactory<Program> fixture every other endpoint test in this project
// uses (there is no separate "ApiTestFactory" type here — see PlatformDashboardEndpointsTests.cs).
public class PlatformInvoicesEndpointsTests : IClassFixture<WebApplicationFactory<Program>>
{
    private readonly WebApplicationFactory<Program> _factory;

    public PlatformInvoicesEndpointsTests(WebApplicationFactory<Program> factory)
    {
        _factory = factory;
    }

    [Fact]
    public async Task ListInvoices_AsSuperAdmin_ReturnsOk()
    {
        var client = _factory.CreateClient();
        var loginResponse = await client.PostAsJsonAsync("/api/v1/platform/auth/login", new { email = "superadmin@courier.local", password = "dev-only-superadmin-password-change-me" });
        var loginBody = await loginResponse.Content.ReadFromJsonAsync<JsonElement>();
        client.DefaultRequestHeaders.Authorization = new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", loginBody.GetProperty("accessToken").GetString());

        var response = await client.GetAsync("/api/v1/platform/invoices");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
    }

    [Fact]
    public async Task ListInvoices_WithoutAuth_ReturnsUnauthorized()
    {
        var client = _factory.CreateClient();

        var response = await client.GetAsync("/api/v1/platform/invoices");

        Assert.Equal(HttpStatusCode.Unauthorized, response.StatusCode);
    }

    // Invoices are generated by billing jobs, not created directly through an endpoint — seeding
    // real invoice rows for a full search/pagination data assertion isn't feasible through this
    // WebApplicationFactory-based test without also driving a full registration + plan-assignment
    // + invoice-generation-job flow (already covered in Billing.Tests/Platform.Tests). This test
    // confirms the new query params reach the endpoint without error and the response shape is a
    // PagedResult (page/pageSize/totalCount/items present), matching PlatformOrganizationsEndpointsTests'
    // established smoke-test style for this file.
    [Fact]
    public async Task ListInvoices_WithSearchAndPagingParams_ReturnsPagedResultShape()
    {
        var client = _factory.CreateClient();
        var loginResponse = await client.PostAsJsonAsync("/api/v1/platform/auth/login", new { email = "superadmin@courier.local", password = "dev-only-superadmin-password-change-me" });
        var loginBody = await loginResponse.Content.ReadFromJsonAsync<JsonElement>();
        client.DefaultRequestHeaders.Authorization = new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", loginBody.GetProperty("accessToken").GetString());

        var response = await client.GetAsync("/api/v1/platform/invoices?search=nonexistent-org-xyz&page=1&pageSize=10");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = await response.Content.ReadFromJsonAsync<JsonElement>();
        Assert.True(body.TryGetProperty("items", out _));
        Assert.Equal(1, body.GetProperty("page").GetInt32());
        Assert.Equal(10, body.GetProperty("pageSize").GetInt32());
        Assert.True(body.TryGetProperty("totalCount", out _));
    }
}
